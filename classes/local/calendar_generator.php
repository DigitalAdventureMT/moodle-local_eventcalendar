namespace local_eventcalendar\local;

use local_eventcalendar\hook\days_created;
use local_eventcalendar\hook\days_deleting;
use local_eventcalendar\hook\restdays_changed;
use local_eventcalendar\persistent\calendar;
use local_eventcalendar\persistent\day;
use local_eventcalendar\persistent\notification_set;
use local_eventcalendar\persistent\iconset;

/**
 * Generation and synchronisation of the days of a calendar.
 *
 * A day is identified by its date (opendate, always UTC): day N falls on startdate + (N - 1) days, and the day
 * number is derived from that date. Missing days (new calendar, extended range) are generated by sync_extend();
 * existing days outside the range are only deleted by delete_days(), after sync_preview() has listed them for
 * confirmation. Remaining days are renumbered by date.
 *
 * Every assigned value is copied into the day row (text for title and body, file for the icon), never linked
 * by a foreign key, so deleting the source notification set or iconset leaves existing days untouched.
 *
 * Random picking works the same for all pools: with a large pool (items >= days to generate) the pool is
 * shuffled and each day gets a different item; with a small pool items are repeated but never on two
 * consecutive days (unless the pool has a single item). Days added later use a new, independent pick.
 *
 * If the calendar comes from a template and a content pack exists for the language chosen in the calendar, the
 * pack supplies the content of the first day, of the last day and a generic pool for the others, plus the
 * calendar tagline (only when still empty). Without a pack these fields stay empty. The language of the user
 * running the generation is never used: see content_pack_repository::get_for_calendar().
 *
 * Other plugins take part through hooks: days_created after new days are generated, restdays_changed after the
 * existing days are realigned to a new rest day setting, days_deleting before days are deleted.
 *
 * The length of a calendar is limited by the "maxdays" setting (get_max_days()), because every day is created
 * in the request that saves the calendar. The limit applies only when days would be created: a calendar
 * already longer than the limit (created before the setting existed, or before it was lowered) keeps its days
 * and can still be edited, as long as its dates do not require new days. The calendar form applies the same
 * rule (exceeds_max_days()), so the error is shown to the user before anything is saved; the check in
 * sync_extend() protects the other callers, such as imports or other plugins.
 *
 * @package     local_eventcalendar
 * @copyright   2026 Marco Tosatto <marco.tosatto@digitaladventure.it>
 * @license     http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class calendar_generator {
    /** Default maximum number of days of a calendar, used when the setting is missing or invalid. */
    public const DEFAULT_MAX_DAYS = 366;

    /**
     * Returns the maximum number of days of a calendar, from the plugin settings.
     *
     * The setting accepts only positive integers; any other stored value (missing, empty, zero) falls back to
     * the default, so the generation is always bounded.
     *
     * @return int
     */
    public static function get_max_days(): int {
        $maxdays = (int) get_config('local_eventcalendar', 'maxdays');

        return $maxdays > 0 ? $maxdays : self::DEFAULT_MAX_DAYS;
    }

    /**
     * Number of days between two dates, both included.
     *
     * The result is rounded so that a daylight saving change between the two dates does not alter it.
     *
     * @param int $startdate
     * @param int $enddate
     * @return int
     */
    public static function count_days(int $startdate, int $enddate): int {
        return (int) round(($enddate - $startdate) / DAYSECS) + 1;
    }

    /**
     * Tells whether a calendar would exceed the maximum length by creating new days.
     *
     * Single rule shared by the form validation and by sync_extend(): no day is created while the calendar
     * is longer than the limit. Without days to create nothing heavy happens, so a calendar that is already
     * too long is accepted as it is.
     *
     * @param int $targetcount number of days of the calendar with the new dates
     * @param int $missingcount number of days that would be created
     * @return bool
     */
    public static function exceeds_max_days(int $targetcount, int $missingcount): bool {
        return $missingcount > 0 && $targetcount > self::get_max_days();
    }

    /**
     * Zero-based index of the day falling on the given date, relative to the calendar start.
     *
     * The result is rounded so that a few seconds of drift do not move the day.
     *
     * @param int $opendate
     * @param int $startdate
     * @return int negative or beyond the number of days = outside the calendar
     */
    private static function day_index(int $opendate, int $startdate): int {
        return (int) round(($opendate - $startdate) / DAYSECS);
    }

    /**
     * Computes what synchronising the days with the given dates would involve, without changing anything.
     *
     * Meant to be called before saving the new dates, so it takes raw values. The caller must ask for
     * confirmation if some days would be deleted.
     *
     * @param int $calendarid
     * @param int $startdate proposed timestamp (not saved yet)
     * @param int $enddate proposed timestamp (not saved yet)
     * @return \stdClass ->missingcount (int, days that would be generated), ->extradays (day[], existing days
     *     that would fall outside the calendar)
     */
    public static function sync_preview(int $calendarid, int $startdate, int $enddate): \stdClass {
        $result = new \stdClass();
        $result->missingcount = 0;
        $result->extradays = [];

        if (empty($startdate) || empty($enddate) || $enddate < $startdate) {
            // Invalid dates are handled by the form validation, nothing to compute.
            return $result;
        }

        $targetcount = self::count_days($startdate, $enddate);

        $covered = [];
        foreach (day::get_records(['calendarid' => $calendarid], 'opendate', 'ASC') as $existingday) {
            $index = self::day_index((int) $existingday->get('opendate'), $startdate);

            if ($index < 0 || $index >= $targetcount) {
                $result->extradays[] = $existingday;
            } else {
                $covered[$index] = true;
            }
        }

        $result->missingcount = $targetcount - count($covered);

        return $result;
    }

    /**
     * Reassigns the day number of existing days from their date and the calendar start date.
     *
     * There is a unique index on (calendarid, daynumber), so new numbers cannot be written one by one: inside
     * a transaction, temporary negative numbers are assigned first, then the final ones. Days outside the
     * calendar are left alone (the caller deletes them beforehand).
     *
     * @param calendar $calendar with the dates already updated
     * @param int $targetcount number of days of the calendar
     * @return int[] numbers of the existing days within the range
     */
    private static function renumber_days(calendar $calendar, int $targetcount): array {
        global $DB;

        $startdate = (int) $calendar->get('startdate');

        $rows = $DB->get_records(
            'local_eventcalendar_days',
            ['calendarid' => $calendar->get('id')],
            'opendate ASC',
            'id, daynumber, opendate'
        );

        $covered = [];
        $changes = [];
        foreach ($rows as $row) {
            $expected = self::day_index((int) $row->opendate, $startdate) + 1;

            if ($expected < 1 || $expected > $targetcount) {
                continue;
            }

            $covered[$expected] = true;

            if ((int) $row->daynumber !== $expected) {
                $changes[(int) $row->id] = $expected;
            }
        }

        if (!empty($changes)) {
            $transaction = $DB->start_delegated_transaction();

            foreach ($changes as $id => $number) {
                $DB->set_field('local_eventcalendar_days', 'daynumber', -$number, ['id' => $id]);
            }
            foreach ($changes as $id => $number) {
                $DB->set_field('local_eventcalendar_days', 'daynumber', $number, ['id' => $id]);
            }

            $transaction->allow_commit();
        }

        return array_keys($covered);
    }

    /**
     * Generates the missing days of a calendar, at the start and/or at the end of the range.
     *
     * Existing days are renumbered first. It covers initial creation and any date change, and is idempotent.
     * Call it after delete_days(), since days outside the calendar could clash with the new day numbers
     * (unique index on calendarid + daynumber).
     *
     * @param calendar $calendar must already reflect the saved dates (after update()/create())
     * @return int number of days actually generated
     * @throws \moodle_exception errortoomanydays if new days are needed and the calendar exceeds the maximum length
     */
    public static function sync_extend(calendar $calendar): int {
        $startdate = (int) $calendar->get('startdate');
        $enddate = (int) $calendar->get('enddate');

        if (empty($startdate) || empty($enddate) || $enddate < $startdate) {
            return 0;
        }

        $targetcount = self::count_days($startdate, $enddate);

        // Renumber existing days by date; the remaining numbers (start, end or both) are the missing ones.
        $covered = self::renumber_days($calendar, $targetcount);

        // The length limit is checked before the list of missing numbers is built: with an unbounded range
        // even range() would allocate one item per day. Renumbering the existing days above is harmless, as
        // it only aligns their numbers to their dates.
        if (self::exceeds_max_days($targetcount, $targetcount - count($covered))) {
            throw new \moodle_exception('errortoomanydays', 'local_eventcalendar', '', self::get_max_days());
        }

        $missingnumbers = array_values(array_diff(range(1, $targetcount), $covered));

        // Content pack of the calendar (template and language chosen in the calendar), if one exists.
        // It is loaded before the early return because the tagline must be filled even when no day is missing.
        $pack = content_pack_repository::get_for_calendar($calendar);

        // The tagline is a single value (not a pool) and is never overwritten once set.
        if ($pack && empty($calendar->get('tagline')) && !empty($pack->tagline)) {
            $calendar->set('tagline', $pack->tagline);
            $calendar->update();
        }

        if (empty($missingnumbers)) {
            return 0;
        }

        $missingcount = count($missingnumbers);

        // Title and body pools from the selected notification set.
        $titlepool = [];
        $bodypool = [];

        $notificationsetid = $calendar->get('notificationsetid');
        if (!empty($notificationsetid) && notification_set::record_exists($notificationsetid)) {
            $notificationset = new notification_set($notificationsetid);
            $titlepool = $notificationset->get_titles();
            $bodypool = $notificationset->get_bodies();
        }

        $titlesequence = self::pick_sequence($titlepool, $missingcount);
        $bodysequence = self::pick_sequence($bodypool, $missingcount);

        // Icon pool from the selected iconset.
        $iconpool = [];

        $iconsetid = $calendar->get('iconsetid');
        if (!empty($iconsetid) && iconset::record_exists($iconsetid)) {
            $iconset = new iconset($iconsetid);
            $iconpool = $iconset->get_items();
        }

        $iconsequence = self::pick_sequence($iconpool, $missingcount);

        // Day content from the pack: first day, last day and generic pool.
        $contentfirst = null;
        $contentlast = null;
        $contentpool = [];

        if ($pack) {
            $contentfirst = $pack->daycontent_first[0] ?? null;
            $contentlast = $pack->daycontent_last[0] ?? null;
            $contentpool = $pack->daycontents ?? [];
        }

        $contentsequence = self::pick_sequence($contentpool, $missingcount);

        // Weekly rest day. The page content comes from the pack's rest day pool when it provides one.
        // Notification title and body always come from the notification set. First and last days with
        // dedicated pack content are not rest days.
        $restenabled = (bool) $calendar->get('restdayenabled');
        $restpool = ($restenabled && $pack) ? ($pack->restday_daycontents ?? []) : [];
        $restweekday = (int) $calendar->get('restdayweekday');

        $restflags = [];
        $restcontentcount = 0;
        if ($restenabled) {
            for ($i = 0; $i < $missingcount; $i++) {
                $daynumber = $missingnumbers[$i];
                $restflags[$daynumber] = self::is_rest_day(
                    $daynumber,
                    $startdate + (($daynumber - 1) * DAYSECS),
                    $targetcount,
                    $restweekday,
                    $contentfirst !== null,
                    $contentlast !== null
                );
                if ($restflags[$daynumber] && !empty($restpool)) {
                    $restcontentcount++;
                }
            }
        }

        // Dedicated pick for rest day content, sized on the days that will actually use it.
        $restsequence = self::pick_sequence($restpool, $restcontentcount);
        $restindex = 0;

        // Days created by this call, passed to the days_created hook.
        $createddays = [];

        // Create only the missing day rows.
        for ($i = 0; $i < $missingcount; $i++) {
            $daynumber = $missingnumbers[$i];
            // First and last day refer to the current calendar configuration, not to this call.
            $isfirstday = ($daynumber === 1);
            $islastday = ($daynumber === $targetcount);

            $newday = new day(0);
            $newday->set('calendarid', $calendar->get('id'));
            $newday->set('daynumber', $daynumber);
            $newday->set('opendate', $startdate + (($daynumber - 1) * DAYSECS));

            $title = $titlesequence[$i] ?? null;
            $body = $bodysequence[$i] ?? null;

            // Title and body always come from the notification set, rest days included.
            $newday->set('notiftitle', $title ? $title->get_message_text() : '');
            $newday->set('notifbody', $body ? $body->get_message_text() : '');
            $newday->set('notifbodyformat', $body ? $body->get('defaultmessageformat') : FORMAT_HTML);

            // Page content: dedicated first/last day content wins, then rest day content, then the generic
            // pool. The rest index advances only when a rest day content is used.
            if ($isfirstday && $contentfirst !== null) {
                $content = $contentfirst;
            } else if ($islastday && $contentlast !== null) {
                $content = $contentlast;
            } else if (!empty($restflags[$daynumber]) && !empty($restpool)) {
                $content = $restsequence[$restindex] ?? '';
                $restindex++;
            } else {
                $content = $contentsequence[$i] ?? '';
            }

            $newday->set('content', $content ?? '');
            $newday->set('contentformat', FORMAT_HTML);

            $newday->create();

            $icon = $iconsequence[$i] ?? null;
            if ($icon) {
                $icon->copy_to_day_filearea($newday->get('id'));
            }

            $createddays[$daynumber] = $newday;
        }

        // Other plugins assign their own values to the new days. The days are passed by increasing number,
        // with the numbers of those that are rest days.
        ksort($createddays);
        $restdaynumbers = array_keys(array_filter($restflags));
        sort($restdaynumbers);
        \core\di::get(\core\hook\manager::class)->dispatch(
            new days_created($calendar, array_values($createddays), $pack, $restdaynumbers)
        );

        return $missingcount;
    }

    /**
     * Tells whether a day is a weekly rest day.
     *
     * Pure function shared by generation and by later changes to the rest day option. The weekday is read from
     * the UTC date (0 = Sunday ... 6 = Saturday). The first and last days are excluded when the pack defines
     * dedicated content for them.
     *
     * @param int $daynumber day number (1-based)
     * @param int $opendate UTC unlock timestamp of the day
     * @param int $daycount total number of days of the calendar
     * @param int $weekday rest weekday, 0 (Sunday) - 6 (Saturday)
     * @param bool $firstconfigured the pack defines content for the first day
     * @param bool $lastconfigured the pack defines content for the last day
     * @return bool
     */
    private static function is_rest_day(
        int $daynumber,
        int $opendate,
        int $daycount,
        int $weekday,
        bool $firstconfigured,
        bool $lastconfigured
    ): bool {
        if ((int) gmdate('w', $opendate) !== $weekday) {
            return false;
        }

        if ($daynumber === 1 && $firstconfigured) {
            return false;
        }

        if ($daynumber === $daycount && $lastconfigured) {
            return false;
        }

        return true;
    }

    /**
     * Numbers of the weekly rest days among the given days, according to the current calendar configuration.
     *
     * The pack is read once per call, so pass all the days to check together. A day is a rest day when the
     * option is enabled, it falls on the configured weekday and it is not a first/last day with dedicated
     * pack content.
     *
     * @param calendar $calendar
     * @param day[] $days days to check (of this calendar)
     * @return int[] rest day numbers, in the received order
     */
    public static function rest_daynumbers(calendar $calendar, array $days): array {
        if (!$calendar->get('restdayenabled') || empty($days)) {
            return [];
        }

        $startdate = (int) $calendar->get('startdate');
        $enddate = (int) $calendar->get('enddate');

        if (empty($startdate) || empty($enddate) || $enddate < $startdate) {
            return [];
        }

        $targetcount = (int) round(($enddate - $startdate) / DAYSECS) + 1;

        $pack = content_pack_repository::get_for_calendar($calendar);

        $firstconfigured = $pack && (($pack->daycontent_first[0] ?? null) !== null);
        $lastconfigured = $pack && (($pack->daycontent_last[0] ?? null) !== null);
        $weekday = (int) $calendar->get('restdayweekday');

        $result = [];
        foreach ($days as $dayitem) {
            $daynumber = (int) $dayitem->get('daynumber');

            if (
                self::is_rest_day(
                    $daynumber,
                    (int) $dayitem->get('opendate'),
                    $targetcount,
                    $weekday,
                    $firstconfigured,
                    $lastconfigured
                )
            ) {
                $result[] = $daynumber;
            }
        }

        return $result;
    }

    /**
     * Single-day shortcut for rest_daynumbers().
     *
     * @param calendar $calendar
     * @param day $day
     * @return bool
     */
    public static function is_day_rest(calendar $calendar, day $day): bool {
        return !empty(self::rest_daynumbers($calendar, [$day]));
    }

    /**
     * Realigns existing days after the weekly rest day option of the calendar has changed.
     *
     * Call it after the calendar update(), with the previous values read before applying the changes, and
     * before sync_extend() and delete_days(). Only the days involved are touched, and never their
     * notifications. Days becoming rest days get rest content from the pack when available; days no longer rest
     * days get generic content, if the pack has rest content. Manual edits to the touched fields are
     * overwritten. Other plugins realign their own values through the restdays_changed hook. If the dates
     * change in the same save, existing days are not regenerated.
     *
     * @param calendar $calendar calendar already updated with the new values
     * @param bool $oldenabled previous value of restdayenabled
     * @param int $oldweekday previous value of restdayweekday
     * @return int number of modified days
     */
    public static function apply_restday_change(calendar $calendar, bool $oldenabled, int $oldweekday): int {
        $newenabled = (bool) $calendar->get('restdayenabled');
        $newweekday = (int) $calendar->get('restdayweekday');

        // Nothing to do when the effective state is unchanged (disabled states are equivalent).
        if ($oldenabled === $newenabled && (!$newenabled || $oldweekday === $newweekday)) {
            return 0;
        }

        $startdate = (int) $calendar->get('startdate');
        $enddate = (int) $calendar->get('enddate');

        if (empty($startdate) || empty($enddate) || $enddate < $startdate) {
            return 0;
        }

        $targetcount = (int) round(($enddate - $startdate) / DAYSECS) + 1;

        $pack = content_pack_repository::get_for_calendar($calendar);

        $restpool = $pack ? ($pack->restday_daycontents ?? []) : [];

        $firstconfigured = $pack && (($pack->daycontent_first[0] ?? null) !== null);
        $lastconfigured = $pack && (($pack->daycontent_last[0] ?? null) !== null);

        // Involved days are decided on the stored UTC date. The day number is derived from the date and the
        // new start, because the stored one may still be the old one. Out of range days are skipped.
        $startdate = (int) $calendar->get('startdate');
        $torestore = [];
        $toapply = [];

        foreach (day::get_records(['calendarid' => $calendar->get('id')], 'opendate', 'ASC') as $dayitem) {
            $opendate = (int) $dayitem->get('opendate');
            $daynumber = self::day_index($opendate, $startdate) + 1;

            if ($daynumber < 1 || $daynumber > $targetcount) {
                continue;
            }

            $wasrest = $oldenabled
                && self::is_rest_day($daynumber, $opendate, $targetcount, $oldweekday, $firstconfigured, $lastconfigured);
            $isrest = $newenabled
                && self::is_rest_day($daynumber, $opendate, $targetcount, $newweekday, $firstconfigured, $lastconfigured);

            if ($wasrest && !$isrest) {
                $torestore[] = $dayitem;
            } else if (!$wasrest && $isrest) {
                $toapply[] = $dayitem;
            }
        }

        // Restore: content from the generic pool only if the pack has rest content. An empty pool gives an
        // empty value.
        $genericpool = $pack ? ($pack->daycontents ?? []) : [];

        $contentrestore = self::pick_sequence($genericpool, count($torestore));
        foreach ($torestore as $i => $dayitem) {
            if (!empty($restpool)) {
                $dayitem->set('content', $contentrestore[$i] ?? '');
                $dayitem->set('contentformat', FORMAT_HTML);
            }
            $dayitem->update();
        }

        // New rest days: rest content when the pack provides it.
        $contentapply = self::pick_sequence($restpool, count($toapply));
        foreach ($toapply as $i => $dayitem) {
            if (!empty($restpool)) {
                $dayitem->set('content', $contentapply[$i] ?? '');
                $dayitem->set('contentformat', FORMAT_HTML);
            }
            $dayitem->update();
        }

        // Other plugins realign the values they keep for the days that changed state.
        if (!empty($torestore) || !empty($toapply)) {
            \core\di::get(\core\hook\manager::class)->dispatch(
                new restdays_changed($calendar, $toapply, $torestore, $pack)
            );
        }

        return count($torestore) + count($toapply);
    }

    /**
     * Permanently deletes the given days with their files, open logs and sent notifications.
     *
     * It takes the days themselves, not their numbers, because numbers shift when the start date changes.
     * It asks for no confirmation: the caller must have obtained it.
     *
     * Before anything is removed the days_deleting hook is dispatched once, with the ids of all the days, so
     * other plugins can delete the data they keep for them.
     *
     * @param day[] $days
     * @return void
     */
    public static function delete_days(array $days): void {
        global $DB;

        if (empty($days)) {
            return;
        }

        $dayids = array_map(static fn(day $dayrecord): int => (int) $dayrecord->get('id'), array_values($days));
        \core\di::get(\core\hook\manager::class)->dispatch(new days_deleting($dayids));

        $context = \context_system::instance();
        $fs = get_file_storage();

        foreach ($days as $dayrecord) {
            $fs->delete_area_files($context->id, 'local_eventcalendar', 'dayicon', $dayrecord->get('id'));
            $fs->delete_area_files($context->id, 'local_eventcalendar', 'content', $dayrecord->get('id'));
            $DB->delete_records('local_eventcalendar_log', ['dayid' => $dayrecord->get('id')]);
            $DB->delete_records('local_eventcalendar_sent', ['dayid' => $dayrecord->get('id')]);

            $dayrecord->delete();
        }
    }

    /**
     * Picks a sequence of $count items from $pool, following the logic described in the class docblock.
     *
     * Public so that other plugins pick their own values (for example the call to action) in the same way.
     *
     * @param array $pool available items (persistent objects or strings)
     * @param int $count number of items required
     * @return array $count items from $pool (repeated if needed), or null values if the pool is empty
     */
    public static function pick_sequence(array $pool, int $count): array {
        $poolsize = count($pool);

        if ($poolsize === 0) {
            return array_fill(0, $count, null);
        }

        $pool = array_values($pool);

        if ($poolsize >= $count) {
            $shuffled = $pool;
            shuffle($shuffled);

            return array_slice($shuffled, 0, $count);
        }

        // Small pool: repeat items but never twice in a row (impossible with a single item).
        $result = [];
        $previouskey = null;

        for ($i = 0; $i < $count; $i++) {
            if ($poolsize === 1) {
                $chosenkey = 0;
            } else {
                do {
                    $chosenkey = array_rand($pool);
                } while ($chosenkey === $previouskey);
            }

            $result[] = $pool[$chosenkey];
            $previouskey = $chosenkey;
        }

        return $result;
    }
}
